    'connections' => [

        'sync' => [
            'driver' => 'sync',
        ],

        /*
         * THE PLATFORM'S DATABASE, NAMED — never "whatever is the default" (B097).
         *
         * Left unset, the jobs table is looked up on the default connection at the
         * moment the queue is first used, and for the whole of an estate request and
         * of every /api/v1 request tenancy has made that the ESTATE's database, which
         * has no `jobs` table. So anything queued there without `CentralQueue::pin()`
         * threw: every statement, receipt, minutes and certificate press 500'd, and
         * the Head of Security's supervisor-override mail — rescued on the guard's
         * clock-in — silently never left. Naming the connection the worker already
         * reads makes the default irrelevant, pinned or not. `DB_QUEUE_CONNECTION`
         * still overrides it for a deployment that keeps its jobs elsewhere.
         */
        'database' => [
            'driver' => 'database',
            'connection' => env('DB_QUEUE_CONNECTION', env('DB_CONNECTION', 'mysql')),
            'table' => env('DB_QUEUE_TABLE', 'jobs'),
            'queue' => env('DB_QUEUE', 'default'),
            'retry_after' => (int) env('DB_QUEUE_RETRY_AFTER', 90),
            'after_commit' => false,
        ],

        /*
         * The SAME central `jobs` table and queue the worker reads, with the
         * database connection named instead of left to the default. A job put on
         * the queue while an estate is open (tenancy makes the estate's database
         * the default) would otherwise be written to a database that has no
         * `jobs` table. The push sender is dispatched from inside estate requests,
         * so it uses this (config/push.php). M4 §3.2.
         */
        'central' => [
            'driver' => 'database',
            'connection' => env('DB_CONNECTION', 'mysql'),
            'table' => env('DB_QUEUE_TABLE', 'jobs'),
            'queue' => env('DB_QUEUE', 'default'),
