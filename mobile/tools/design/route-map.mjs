// M43 §13: the Resident App's complete route map — every screen, and every place in the app that opens it — so a
// screen the rebuild deletes ("Your community", M42 E4) is never the only door to another one.
//
// Reads every navigation the routes gate reads (router.push / replace / navigate, go(), open(), href=, pathname:)
// in apps/resident/src, apps/resident/app and packages/core, plus the notification table (packages/core/notify/
// links.ts), and writes _design/RESIDENT_ROUTE_MAP.md: per route, the files that lead to it. A route with one door
// is marked; a route whose only doors are in a file the rebuild removes is the trap §13 asks about.
//
//   node tools/design/route-map.mjs

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SKIP = new Set(['node_modules', 'lifted', '.expo', 'dist', 'android', 'ios', '__tests__', 'gallery', 'fidelity'])
const walk = (dir) => readdirSync(dir).flatMap((n) => (SKIP.has(n) ? [] : statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : /\.tsx?$/.test(n) ? [join(dir, n)] : []))
const appDir = join(root, 'apps', 'resident', 'app')

const routes = walk(appDir)
  .map((f) => relative(appDir, f).replace(/\\/g, '/').replace(/\.tsx?$/, ''))
  .filter((r) => !/(^|\/)(_layout|\+not-found|\+html|\+native-intent)$/.test(r))
  .map((r) => ({ file: r, segs: r.split('/').filter((s) => !/^\(.*\)$/.test(s)).filter((s, i, all) => !(s === 'index' && i === all.length - 1)) }))
const matches = (segs, target) => segs.length === target.length && segs.every((s, i) => /^\[.*\]$/.test(s) || s === target[i])

const CALL = /(?:router\.(?:push|replace|navigate)|\bgo|\bopen|\benterApp|href\s*=\s*\{?|pathname\s*:)\s*\(?\s*(['"`])(\/[^'"`]*)\1/g
const doors = new Map(routes.map((r) => [r.file, []]))
const sources = [...walk(join(root, 'apps', 'resident', 'src')), ...walk(appDir), ...walk(join(root, 'packages', 'core'))]
for (const file of sources) {
  const src = readFileSync(file, 'utf8')
  const rel = relative(root, file).replace(/\\/g, '/')
  const isLinks = rel === 'packages/core/notify/links.ts'
  const found = isLinks
    ? [...(/const RESIDENT[\s\S]*?=\s*\{([\s\S]*?)\n\}/.exec(src)?.[1] ?? '').matchAll(/(['"`])(\/[^'"`\n]*)\1/g)].map((m) => m[2])
    : [...src.matchAll(CALL)].map((m) => m[2])
  for (const raw of found) {
    const target = raw.split('?')[0].replace(/\$\{[^}]*\}/g, '·').split('/').filter(Boolean).filter((s) => !/^\(.*\)$/.test(s))
    for (const r of routes) if (matches(r.segs, target)) doors.get(r.file).push(isLinks ? 'a notification (links.ts)' : rel.replace(/^apps\/resident\/src\/features\//, ''))
  }
}

const tabs = new Set(['(tabs)/index', '(tabs)/visitors', '(tabs)/notices', '(tabs)/dues', '(tabs)/profile'])
const lines = ['# Resident App route map (M43 §13)', '', 'Generated by `node tools/design/route-map.mjs`. Every route, and every file that opens it (a tab is always reachable from the tab bar). "ONE DOOR" marks a route only one file opens.', '', '| route | doors | opened from |', '|---|---|---|']
for (const r of routes.sort((a, b) => a.file.localeCompare(b.file))) {
  const from = [...new Set(doors.get(r.file))].sort()
  const tab = tabs.has(r.file) ? ['the tab bar'] : []
  const all = [...tab, ...from]
  const flag = all.length === 0 ? '**NONE**' : all.length === 1 ? '**ONE DOOR**' : String(all.length)
  lines.push(`| /${r.file} | ${flag} | ${all.join(', ') || '—'} |`)
}
writeFileSync(join(root, '_design', 'RESIDENT_ROUTE_MAP.md'), lines.join('\n') + '\n', 'utf8')
