// M42 §2: EXTRACT the values, do not eyeball them.
//
// Reads every <style> rule in the ten Resident App screen files (the client's approved HTML, byte-identical to
// `_design/wireframes/`) and writes `_design/RESIDENT_VALUES.json`: every distinct value per property, each with
// the selectors that use it and the files they are in. The token module (apps/resident/src/design/tokens.ts) is
// written from this file and checked against it — a value the screens use that the token module does not name
// fails `npm run design:tokens:resident -- --check`.
//
// Device chrome (the bezel, the island, the status bar, the home indicator) and board presentation (the intro,
// the chips above each phone, the flow connectors) are not the app: their rules are left out, by selector.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, '_design', 'wireframes', 'GeminiSecure Resident App Screens')
const out = join(root, '_design', 'RESIDENT_VALUES.json')

// Rules that draw the board or the physical phone, never the app.
const CHROME = /^(body|\*|\.intro\b|\.board\b|\.stage\b|\.chip\b(?!-)|\.connector\b|\.device\b|\.screen\b|\.island\b|\.home-ind\b|\.statusbar\b|:root)/

const PROPS = {
  colour: ['color', 'background', 'background-color', 'border-color', 'border', 'border-top', 'border-bottom', 'border-left', 'border-right', 'box-shadow', 'stroke', 'fill'],
  type: ['font-family', 'font-size', 'font-weight', 'line-height', 'letter-spacing', 'text-transform', 'font-style'],
  space: ['padding', 'padding-top', 'padding-bottom', 'padding-left', 'padding-right', 'margin', 'margin-top', 'margin-bottom', 'margin-left', 'margin-right', 'gap', 'top', 'bottom', 'left', 'right'],
  size: ['width', 'height', 'min-height', 'max-width', 'flex'],
  radius: ['border-radius', 'border-top-left-radius', 'border-top-right-radius', 'border-bottom-left-radius', 'border-bottom-right-radius'],
  shadow: ['box-shadow'],
}

const vars = {}
const uses = {} // property -> value -> { selectors:Set, files:Set }
const record = (prop, value, selector, file) => {
  uses[prop] ??= {}
  uses[prop][value] ??= { selectors: new Set(), files: new Set() }
  uses[prop][value].selectors.add(selector)
  uses[prop][value].files.add(file)
}

const files = readdirSync(dir).filter((f) => f.endsWith('.html')).sort()
for (const file of files) {
  const html = readFileSync(join(dir, file), 'utf8')
  const css = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n').replace(/\/\*[\s\S]*?\*\//g, '')
  for (const [, sel, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = sel.trim().replace(/\s+/g, ' ')
    for (const decl of body.split(';')) {
      const at = decl.indexOf(':')
      if (at < 0) continue
      const prop = decl.slice(0, at).trim().toLowerCase()
      const value = decl.slice(at + 1).trim().replace(/\s+/g, ' ')
      if (!prop || !value) continue
      if (selector === ':root' && prop.startsWith('--')) { (vars[prop] ??= new Set()).add(value); continue }
      if (selector.split(',').every((s) => CHROME.test(s.trim()))) continue
      record(prop, value, selector, file)
    }
  }
  // Inline styles carry real values too (a margin-top on one field, a width on one bar).
  for (const [, style] of html.matchAll(/style="([^"]*)"/g)) {
    for (const decl of style.split(';')) {
      const at = decl.indexOf(':')
      if (at < 0) continue
      record(decl.slice(0, at).trim().toLowerCase(), decl.slice(at + 1).trim(), '[inline]', file)
    }
  }
}

const shape = (props) => Object.fromEntries(props.filter((p) => uses[p]).map((p) => [p, Object.fromEntries(Object.entries(uses[p]).sort().map(([v, u]) => [v, { selectors: [...u.selectors].sort(), files: [...u.files].sort() }]))]))
const result = {
  note: 'Generated by tools/design/resident-values.mjs from _design/wireframes/GeminiSecure Resident App Screens/*.html. Do not edit by hand.',
  files,
  rootVariables: Object.fromEntries(Object.entries(vars).sort().map(([k, v]) => [k, [...v]])),
  ...Object.fromEntries(Object.entries(PROPS).map(([k, props]) => [k, shape(props)])),
}

if (process.argv.includes('--check')) {
  const was = readFileSync(out, 'utf8')
  if (was !== JSON.stringify(result, null, 2) + '\n') { console.error('RESIDENT_VALUES.json is out of date: run node tools/design/resident-values.mjs'); process.exit(1) }
  console.log('RESIDENT_VALUES.json is current')
} else {
  writeFileSync(out, JSON.stringify(result, null, 2) + '\n', 'utf8')
  const count = (k) => Object.values(result[k]).reduce((n, v) => n + Object.keys(v).length, 0)
  console.log(`wrote ${out}: ${files.length} files · ${Object.keys(result.rootVariables).length} :root variables · colour ${count('colour')} · type ${count('type')} · space ${count('space')} · size ${count('size')} · radius ${count('radius')} values`)
}
